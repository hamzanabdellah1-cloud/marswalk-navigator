"""Build data/grid.js from the cropped Gale DEM.

The page never calls this. Run it once after the DEM crop or the map frame changes.
The three map images must use the same bounds as assets/maps/frame.json.
"""

import json
import math
from pathlib import Path

import numpy as np
import rasterio
from scipy.ndimage import uniform_filter, zoom

ROOT = Path(__file__).resolve().parents[1]
DEM_PATH = ROOT / "data" / "gale_dem_crop.tif"
FRAME_PATH = ROOT / "assets" / "maps" / "frame.json"
OUT_PATH = ROOT / "data" / "grid.js"

MAX_CELLS = 300
MARS_RADIUS_M = 3389500.0
SOURCE = (
    "USGS Astrogeology / MSL project, MSL Gale DEM Mosaic, 1 m, "
    "via NASA/JPL Mars Trek"
)


def ground_size(bounds):
    mid_lat = (bounds["south"] + bounds["north"]) / 2.0
    meters_per_degree_lat = MARS_RADIUS_M * math.pi / 180.0
    meters_per_degree_lon = meters_per_degree_lat * math.cos(math.radians(mid_lat))
    width_m = (bounds["east"] - bounds["west"]) * meters_per_degree_lon
    height_m = (bounds["north"] - bounds["south"]) * meters_per_degree_lat
    return width_m, height_m


def read_dem():
    with rasterio.open(DEM_PATH) as src:
        values = src.read(1).astype(np.float64)
        nodata = src.nodata
        transform = src.transform
        has_bounds = src.crs is not None and transform.a not in (0, 1) and abs(transform.a) > 1e-8
        raster_bounds = None
        pixel_m = None
        if has_bounds:
            raster_bounds = {
                "west": float(src.bounds.left),
                "south": float(src.bounds.bottom),
                "east": float(src.bounds.right),
                "north": float(src.bounds.top),
            }
        if nodata is not None:
            values[values == nodata] = np.nan
    return values, raster_bounds, pixel_m


def target_shape(rows, cols):
    long_side = max(rows, cols)
    if long_side <= MAX_CELLS:
        return rows, cols
    scale = MAX_CELLS / long_side
    return max(2, int(round(rows * scale))), max(2, int(round(cols * scale)))


def ridge_score(elev):
    """Topographic position index, scaled to 0–1. A heuristic, not a measurement."""
    filled = np.where(np.isfinite(elev), elev, 0.0)
    local_mean = uniform_filter(filled, size=9, mode="nearest")
    tpi = filled - local_mean
    finite = tpi[np.isfinite(elev)]
    low, high = np.percentile(finite, [2, 98])
    span = high - low
    if span <= 0:
        return np.zeros_like(elev)
    return np.clip((tpi - low) / span, 0.0, 1.0)


def compact(values, digits):
    return ",".join(format(float(value), f".{digits}f") for value in values)


def main():
    frame = json.loads(FRAME_PATH.read_text(encoding="utf-8"))
    elev, raster_bounds, _pixel_m = read_dem()
    bounds = raster_bounds or {
        "west": frame["west"],
        "south": frame["south"],
        "east": frame["east"],
        "north": frame["north"],
    }
    valid = np.isfinite(elev)
    if not np.any(valid):
        raise SystemExit("DEM has no elevation values.")

    rows, cols = target_shape(elev.shape[0], elev.shape[1])
    if (rows, cols) != elev.shape:
        elev = zoom(np.where(valid, elev, np.nanmean(elev)), (rows / elev.shape[0], cols / elev.shape[1]), order=1)
        valid = np.ones(elev.shape, dtype=bool)

    width_m, height_m = ground_size(bounds)
    cell_x = width_m / elev.shape[1]
    cell_y = height_m / elev.shape[0]
    cell_size_m = (cell_x + cell_y) / 2.0
    dz_dy, dz_dx = np.gradient(elev, cell_y, cell_x)
    slope = np.degrees(np.arctan(np.hypot(dz_dx, dz_dy)))
    interest = ridge_score(elev)
    slope = np.where(valid, slope, 0.0)
    interest = np.where(valid, interest, 0.0)

    # This crop is the 1 m mosaic, not the coarse CTX/HRSC fill.
    resolution_m = 1
    grid = {
        "bounds": bounds,
        "width": int(elev.shape[1]),
        "height": int(elev.shape[0]),
        "cell_size_m": round(cell_size_m, 3),
        "resolution_m": resolution_m,
        "coarse_fill": False,
        "source": SOURCE,
        "width_m": round(width_m, 1),
        "height_m": round(height_m, 1),
    }
    body = (
        "/* Generated by tools/build_grid.py. Do not edit by hand. */\n"
        "window.MARSWALK_GRID = {\n"
        f"bounds:{json.dumps(grid['bounds'])},\n"
        f"width:{grid['width']},height:{grid['height']},\n"
        f"cell_size_m:{grid['cell_size_m']},resolution_m:{grid['resolution_m']},\n"
        f"coarse_fill:{'true' if grid['coarse_fill'] else 'false'},\n"
        f"width_m:{grid['width_m']},height_m:{grid['height_m']},\n"
        f"source:{json.dumps(grid['source'])},\n"
        f"elev:[{compact(np.round(elev, 1).ravel(), 1)}],\n"
        f"slope:[{compact(np.round(slope, 2).ravel(), 2)}],\n"
        f"interest:[{compact(np.round(interest, 3).ravel(), 3)}],\n"
        f"nodata:[{compact(np.where(valid, 0, 1).ravel().astype(np.int8), 0)}]\n"
        "};\n"
    )
    OUT_PATH.write_text(body, encoding="utf-8")
    finite_slope = slope[valid]
    print(
        f"wrote {OUT_PATH} {OUT_PATH.stat().st_size} bytes "
        f"{grid['width']}x{grid['height']} cell {grid['cell_size_m']} m "
        f"slope median {np.median(finite_slope):.2f} "
        f"p90 {np.percentile(finite_slope, 90):.2f} "
        f"max {finite_slope.max():.2f}"
    )


if __name__ == "__main__":
    main()
